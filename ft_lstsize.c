#include "libft.h"

unsigned int	ft_lstsize(t_list *lst)
{
	unsigned int	len;

	if (!lst)
		return (0);
	len = 0;
	while (lst)
	{
		len++;
		lst = lst->next;
	}
	return (len);
}
